import { openSettingsService } from "./test-helpers/settings-ui.mjs";
import { chromium, expect } from "@playwright/test";
import { createServer } from "vite";
import { resolve } from "node:path";
import { launchChromiumForSmoke } from "./test-helpers/playwright-browser.mjs";

const server = await createServer({ root: resolve("apps/desktop-app"), configFile: resolve("apps/desktop-app/vite.renderer.config.ts"), server: { port: 0, strictPort: false } });
let browser;
try {
  await server.listen();
  browser = await launchChromiumForSmoke(chromium);
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: "tr-TR" });
  page.setDefaultTimeout(7000);
  const errors = [], uploads = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (request.url().includes("audio-transcribe")) uploads.push(request.url()); });
  await page.route("**/voice-settings-test", async route => route.fulfill({ contentType: "text/html", body: await server.transformIndexHtml("/voice-settings-test",
    `<html><body><div id="root"></div><script type="module" src="/@fs/${resolve("scripts/fixtures/settings-platform.tsx")}"></script></body></html>`) }));
  await page.route(/^https:\/\/(?:[^/]+\.)?tile\.openstreetmap\.org\//, route => route.abort());
  await page.goto(`${server.resolvedUrls.local[0]}voice-settings-test`);
  const services = () => openSettingsService(page, "settings-ai");
  await services();
  const ai = page.locator(".settings-service-overlay");
  const stt = ai.getByLabel("Konuşma tanıma modeli (STT)", { exact: true });
  const provider = ai.locator(".setup-ai-service-field select");
  const save = ai.getByRole("button", { name: "Kaydet", exact: true });
  const discard = ai.getByRole("button", { name: "İptal", exact: true });
  await expect(stt).toBeDisabled();
  await ai.getByRole("switch", { name: "AI Yardımcı servisi" }).check();
  await expect(stt).toHaveValue("");
  await ai.getByLabel("Model adı", { exact: true }).fill("gpt-4.1");
  await ai.getByLabel("Görsel üretim modeli", { exact: true }).selectOption("gpt-image-1");
  await ai.getByLabel("AI güvenlik anahtarı", { exact: true }).fill("fixture-ui-ai-key");
  expect(await stt.locator("option").evaluateAll(options => options.map(option => option.value))).toEqual(["", "gpt-4o-mini-transcribe", "gpt-4o-transcribe", "whisper-1"]);
  await stt.selectOption("whisper-1");
  await provider.selectOption("gemini");
  await expect(stt).toHaveValue("");
  expect(await stt.locator("option").evaluateAll(options => options.map(option => option.value))).toEqual(["", "gemini-3.6-flash", "gemini-3.8-flash", "gemini-2.5-flash"]);
  await ai.getByLabel("Google AI Studio API anahtarı veya cURL", { exact: true }).fill("fixture-ui-google-key");
  await ai.getByRole("button", { name: "Bağlantıyı Dene", exact: true }).click();
  await expect(ai.locator("#settings-ai-test")).toHaveClass(/sync-success/);
  await stt.selectOption("gemini-3.6-flash");
  await provider.selectOption("openai");
  await expect(stt).toHaveValue("whisper-1");
  await expect(ai.getByLabel("Model adı", { exact: true })).toHaveValue("gpt-4.1");
  await expect(ai.getByLabel("Görsel üretim modeli", { exact: true })).toHaveValue("gpt-image-1");
  await ai.getByRole("button", { name: "Bağlantıyı Dene", exact: true }).click();
  await expect(ai.locator("#settings-ai-test")).toHaveClass(/sync-success/);
  await page.evaluate(() => { window.failSetup = true; });
  await save.click();
  await expect(page.getByText("Test kayıt hatası", { exact: true }).first()).toBeVisible();
  await expect(stt).toHaveValue("whisper-1");
  await expect(save).toBeEnabled();
  await page.evaluate(() => { window.failSetup = false; window.delaySetup = true; });
  await save.click();
  await expect(stt).toBeDisabled();
  await page.evaluate(() => { window.finishSetup(); window.delaySetup = false; });
  await expect(ai).toHaveCount(0);
  await services();
  const profiles = await page.evaluate(() => window.settingsCalls.filter(call => call.kind === "setup").at(-1).input.aiProfiles);
  expect(profiles.find(profile => profile.service === "openai").sttModel).toBe("whisper-1");
  expect(profiles.find(profile => profile.service === "gemini").sttModel).toBe("gemini-3.6-flash");
  await stt.selectOption("gpt-4o-transcribe");
  await expect(discard).toBeEnabled();
  for (const service of ["groq", "openrouter", "custom"]) {
    await provider.selectOption(service);
    await expect(stt).toBeDisabled();
    await expect(stt).toHaveValue("");
    await expect(ai.getByText("Sağlayıcının STT desteği yok.", { exact: true })).toBeVisible();
  }
  await discard.click();
  await services();
  await expect(provider).toHaveValue("openai");
  await expect(stt).toHaveValue("whisper-1");
  await provider.selectOption("gemini");
  await expect(stt).toHaveValue("gemini-3.6-flash");
  await stt.selectOption("");
  await discard.click();
  await services();
  await provider.selectOption("gemini");
  await expect(stt).toHaveValue("gemini-3.6-flash");
  await discard.click();
  await services();
  await discard.click();
  await page.evaluate(() => window.reopenSettings());
  await services();
  await expect(stt).toHaveValue("whisper-1");
  await stt.selectOption("");
  await save.click();
  await expect(ai).toHaveCount(0);
  await services();
  expect(await page.evaluate(() => window.settingsCalls.filter(call => call.kind === "setup").at(-1).input.aiSttModel)).toBe("");
  await provider.selectOption("cloudflare");
  await expect(stt).toHaveValue("");
  await ai.getByLabel("Cloudflare Account ID", { exact: true }).fill("a".repeat(32));
  await ai.getByLabel("Metin modeli", { exact: true }).selectOption("@cf/zai-org/glm-4.7-flash");
  await ai.getByLabel("Görsel analiz modeli", { exact: true }).selectOption("@cf/meta/llama-4-scout-17b-16e-instruct");
  await ai.getByLabel("Görsel üretim modeli", { exact: true }).selectOption("@cf/black-forest-labs/flux-1-schnell");
  await stt.selectOption("@cf/openai/whisper-large-v3-turbo");
  await ai.getByLabel("Cloudflare API Token", { exact: true }).fill("fixture-ui-cloudflare-token");
  await ai.getByRole("button", { name: "Bağlantıyı Dene", exact: true }).click();
  await expect(ai.locator("#settings-ai-test")).toHaveClass(/sync-success/);
  const cfTest = await page.evaluate(() => window.settingsCalls.filter(call => call.kind === "ai-test").at(-1).input);
  expect(cfTest.baseUrl).toBe(`https://api.cloudflare.com/client/v4/accounts/${"a".repeat(32)}/ai`);
  expect(cfTest.visionModel).toBe("@cf/meta/llama-4-scout-17b-16e-instruct");
  await ai.getByLabel("Görsel analiz modeli", { exact: true }).selectOption("");
  await expect(ai.locator("#settings-ai-test")).toHaveClass(/sync-idle/);
  await provider.selectOption("gemini");
  await expect(stt).toHaveValue("gemini-3.6-flash");
  await provider.selectOption("cloudflare");
  await expect(ai.getByLabel("Cloudflare Account ID", { exact: true })).toHaveValue("a".repeat(32));
  await expect(stt).toHaveValue("@cf/openai/whisper-large-v3-turbo");
  await expect(ai.getByLabel("Görsel üretim modeli", { exact: true })).toHaveValue("@cf/black-forest-labs/flux-1-schnell");
  await save.click();
  await expect(ai).toHaveCount(0);
  await services();
  await discard.click();
  await page.evaluate(() => window.reopenSettings());
  await services();
  await expect(provider).toHaveValue("cloudflare");
  await expect(stt).toHaveValue("@cf/openai/whisper-large-v3-turbo");
  expect(uploads).toEqual([]);
  expect(errors).toEqual([]);
  console.log("voice-stt-ui-smoke-ok: real Settings controls, provider drafts, failed save, busy, discard, reopen and explicit OFF");
} finally { await browser?.close(); await server.close(); }
