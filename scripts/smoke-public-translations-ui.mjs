import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { resolve } from "node:path";
import { createServer } from "vite";
import { chromium, expect } from "@playwright/test";
import { launchChromiumForSmoke } from "./test-helpers/playwright-browser.mjs";
const require = createRequire(import.meta.url);
const {PublicTranslationStore} = require("../apps/desktop-app/dist-electron/database/public-translation-store.js");
const db = new DatabaseSync(":memory:");
db.exec(readFileSync("apps/desktop-app/db/schema.sql","utf8"));
db.exec("INSERT INTO business(id,name,display_name,profile_id,created_at,updated_at) VALUES ('b','Market','Market','market','t','t'); INSERT INTO business_capabilities(business_id,capability_id,created_at,updated_at) VALUES ('b','channel.online_sales','t','t');");
db.exec("BEGIN");
const insert=db.prepare("INSERT INTO catalog_products(id,business_id,name,description,created_at,updated_at) VALUES (?,'b',?,'Taze ürün','t','t')");
const publish=db.prepare("INSERT INTO commerce_product_publications(product_id,business_id,channel,is_published,created_at,updated_at) VALUES (?,'b','online_sales',1,'t','t')");
for(let n=0;n<10000;n++){insert.run(`p${n}`,`Ürün ${String(n).padStart(5,"0")}`);publish.run(`p${n}`);}
db.exec("COMMIT");
const store=new PublicTranslationStore(db);
const rawChange=()=>db.exec("UPDATE catalog_products SET name='Ürün 09999 yeni' WHERE id='p9999'");
const server=await createServer({root:resolve("apps/desktop-app"),configFile:resolve("apps/desktop-app/vite.renderer.config.ts"),server:{port:0,strictPort:false}});
await server.listen();
const emptyDb = new DatabaseSync(":memory:");
emptyDb.exec(readFileSync("apps/desktop-app/db/schema.sql","utf8"));
emptyDb.exec("INSERT INTO business(id,name,display_name,profile_id,created_at,updated_at) VALUES ('empty','Empty','Empty','market','t','t')");
const emptyStore = new PublicTranslationStore(emptyDb);
emptyStore.saveSettings({enabled:true,sourceLanguage:"tr",targetLanguages:["en"],automatic:false});
let listMode = "full";
let browser;
try {
  browser=await launchChromiumForSmoke(chromium);
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.route("**/fixture-translations/*",async route=>{
    try {
      const input=route.request().postDataJSON(),method=new URL(route.request().url()).pathname.split("/").at(-1);
      if (method === "list" && listMode === "error") return route.fulfill({json:{ok:false,message:"Fixture: public kaynak okunamadı"}});
      if (method === "list" && listMode === "rejected") return route.fulfill({status:503,body:"fixture unavailable"});
      const value=method==="settings"?store.settings():method==="saveSettings"?store.saveSettings(input):method==="get"?store.get(input.identity,input.language):method==="list"?(listMode === "empty" ? emptyStore : store).list(input):method==="save"?store.saveManual(input):null;
      if(method==="start")throw Error("AI yapılandırılmamış. Manuel çeviri kullanabilirsiniz.");
      await route.fulfill({json:{ok:true,value}});
    } catch(error){await route.fulfill({json:{ok:false,message:error.message}});}
  });
  await page.route("**/translation-ui-test*",async route=>route.fulfill({contentType:"text/html",body:await server.transformIndexHtml("/translation-ui-test",`<html><body><div id="root"></div><script type="module" src="/@fs/${resolve("scripts/fixtures/settings-platform.tsx")}"></script></body></html>`)}));
  await page.goto(`${server.resolvedUrls.local[0]}translation-ui-test?profile=market&translations=on`);
  await expect(page.getByRole("button",{name:"Dil Yönetimi",exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:/^İşletme Yapısı ve Özellikler/}).click();
  await page.getByRole("button",{name:"Çoklu Dil ayarları"}).click();
  await expect(page.locator("dialog[open]")).toHaveCount(1);
  const service=page.getByRole("dialog",{name:"Çoklu Dil",exact:true});
  await expect(service.getByLabel("Hedef yayın dili")).toBeDisabled();
  await service.getByRole("switch",{name:"Çoklu Dil servisi"}).check();
  await expect(service.getByRole("status")).toContainText("AI etkin değil");
  await service.getByLabel("Hedef yayın dili").selectOption("de");
  await service.getByRole("button",{name:"Hedef Dili Ekle"}).click();
  await service.getByLabel("Hedef yayın dili").selectOption("fr");
  await service.getByRole("button",{name:"Hedef Dili Ekle"}).click();
  await service.getByRole("button",{name:"Kaydet",exact:true}).click();
  await expect(service).toBeHidden();
  assert.deepEqual(store.settings().targetLanguages,["de","fr"]);
  assert.equal(store.settings().automatic,true);
  await page.getByRole("button",{name:"Çoklu Dil ayarları"}).click();
  await service.getByRole("button",{name:"Almanca dilini kaldır"}).click();
  await service.getByRole("button",{name:"Fransızca dilini kaldır"}).click();
  await service.getByLabel("Hedef yayın dili").selectOption("en");
  await service.getByRole("button",{name:"Hedef Dili Ekle"}).click();
  await service.getByRole("button",{name:"Kaydet",exact:true}).click();
  await expect(service).toBeHidden();
  assert.equal(store.settings().enabled,true,await page.locator("body").innerText());
  await expect(page.getByRole("button",{name:"Oda Yönetimi",exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:"Dil Yönetimi",exact:true}).click();
  const workspace=page.getByRole("dialog",{name:"Dil Yönetimi",exact:true});
  await expect(workspace.locator(".list-row")).toHaveCount(50);
  await expect(workspace).toContainText("10000 kayıt");
  const search=workspace.getByRole("searchbox",{name:"Kayıtlarda ara"});
  await search.fill("ürün 09999");
  await expect(workspace.locator(".list-row")).toHaveCount(1);
  const recordButton=workspace.getByRole("button",{name:"Ürün 09999",exact:true});
  const rowBounds=await recordButton.boundingBox();
  assert.ok(rowBounds,"Translation row must be visible");
  await recordButton.click({position:{x:rowBounds.width-5,y:rowBounds.height/2}});
  await expect(workspace.getByLabel(/Türkçe$/)).toHaveCount(2);
  await expect(workspace.locator(".language-workspace__record.is-selected")).toHaveCount(1);
  assert.equal(await workspace.locator(".language-workspace__record.is-selected input[type=checkbox]").isChecked(),true,"Record click selects its checkbox");
  await page.screenshot({path:"/tmp/yardimci-translations-desktop-polished.png"});
  await workspace.getByLabel(/en çeviri$/).first().fill("English product");
  await expect(workspace.getByRole("button",{name:"Dil Yönetimini kapat"})).toBeDisabled();
  await page.keyboard.press("Escape"); await expect(workspace).toBeVisible();
  await workspace.getByRole("button",{name:"Kaydet",exact:true}).click();
  await expect(workspace.getByRole("button",{name:"Dil Yönetimini kapat"})).toBeEnabled();
  assert.equal(db.prepare("SELECT origin FROM public_translations WHERE record_id='p9999'").get().origin,"manual");
  await workspace.getByRole("button",{name:"AI ile Çevir",exact:true}).click();
  await expect(workspace.getByRole("alert")).toContainText("AI yapılandırılmamış");
  await expect(workspace.getByLabel(/en çeviri$/).first()).toHaveValue("English product");
  rawChange();
  await workspace.getByRole("button",{name:"Yenile",exact:true}).click();
  await expect(workspace).toContainText("Manuel çeviriyi yeni kaynakla karşılaştırın");
  await workspace.getByRole("button",{name:"Kaydet",exact:true}).click();
  await expect(workspace).not.toContainText("Manuel çeviriyi yeni kaynakla karşılaştırın");
  assert.equal(store.get({kind:"catalog_product",id:"p9999"},"en").stale,0);
  await page.setViewportSize({width:600,height:850});
  await expect(workspace.getByRole("button",{name:"Kayıtlara Dön"})).toBeVisible();
  await workspace.getByRole("button",{name:"Kayıtlara Dön"}).click();
  await expect(search).toHaveValue("ürün 09999");
  await workspace.getByRole("button",{name:"İşlem Paneli"}).click();
  await expect(workspace.getByLabel(/en çeviri$/).first()).toHaveValue("English product");
  assert.equal(await workspace.evaluate(n=>n.scrollWidth>n.clientWidth+1),false,"narrow workspace overflow");
  await expect(page.locator("dialog[open]")).toHaveCount(1);
  await page.screenshot({path:"/tmp/yardimci-translations-mobile.png"});
  await workspace.getByRole("button",{name:"Kayıtlara Dön"}).click();
  await search.fill("does-not-exist");
  await expect(workspace.getByRole("status")).toContainText("Filtreye uygun public kayıt bulunamadı");
  await search.fill("");
  await expect(workspace).toContainText("10000 kayıt");
  listMode = "error";
  await workspace.getByRole("button",{name:"Yenile",exact:true}).click();
  await expect(workspace).toContainText("Kayıt sayısı alınamadı");
  await expect(workspace.getByRole("alert")).toContainText("Fixture: public kaynak okunamadı");
  await expect(workspace).not.toContainText("0 kayıt ·");
  await expect(workspace.getByRole("button",{name:"Sayfayı Seç"})).toBeDisabled();
  await workspace.getByRole("button",{name:"Dil Yönetimini kapat"}).click();
  // A first-load rejected IPC/read must also be different from a real empty source database.
  listMode = "rejected";
  await page.getByRole("button",{name:"Dil Yönetimi",exact:true}).click();
  await expect(workspace.getByRole("alert")).toContainText("Kayıtlar okunamadı");
  await expect(workspace).not.toContainText("Henüz çevrilebilir public kaynak kaydı yok");
  listMode = "empty";
  await workspace.getByRole("button",{name:"Yenile",exact:true}).click();
  await expect(workspace.getByRole("status")).toContainText("Henüz çevrilebilir public kaynak kaydı yok");
  await expect(workspace.locator(".language-workspace__count")).toHaveText("0 kayıt");
  await expect(workspace.locator(".language-workspace__selection-count")).toHaveText("0 seçili");
  await expect(workspace.getByRole("alert")).toHaveCount(0);
  listMode = "full";
  await workspace.getByRole("button",{name:"Yenile",exact:true}).click();
  await expect(workspace.locator(".list-row")).toHaveCount(50);
  await expect(workspace).toContainText("10000 kayıt");
  assert.deepEqual(errors,[]);
  console.log("Translation UI: Market visibility, service drafts, 10000 records/50 DOM rows, search, manual save, unavailable AI, dirty close and responsive state, empty/full source fixtures and first-load/retry read errors OK.");
} finally {await browser?.close();await server.close();db.close();emptyDb.close();}
