import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { resolve } from 'node:path';
const server = await createServer({ root: resolve('apps/desktop-app'), configFile: resolve('apps/desktop-app/vite.renderer.config.ts'), server: { middlewareMode: true } });
try {
  const { getRoomCardModel: roomModel } = await server.ssrLoadModule('/src/components/pension/room-card-model.ts');
  const { getTableCardModel: tableModel } = await server.ssrLoadModule('/src/components/restaurant/table-card-model.ts');
  const caps = { staysEnabled: true, folioEnabled: true, reservationsEnabled: true, ordersEnabled: true, menuEnabled: true };
  const room = { id: 'room', capacity: 2, status: 'available', isActive: true };
  const stay = { id: 'current', status: 'checked_in', checkInDate: '2030-01-01', checkOutDate: '2030-01-04' };
  const reservation = { id: 'booking', customerId: 'same-guest', status: 'approved', startDate: '2030-01-05', endDate: '2030-01-07', guestCount: 2 };
  const old = { folioId: 'old-folio', stayId: 'old-stay', stayStatus: 'checked_out', remainingMinor: 10000 };
  const current = { folioId: 'current-folio', stayId: stay.id, stayStatus: stay.status, remainingMinor: 20000 };
  const summary = { roomId: room.id, stays: [stay], reservations: [reservation], accounts: [old, current] };
  const model = (r = room, s = summary, c = caps) => roomModel(r, s, c, '2030-01-02');
  assert.equal(model().currentAccount.folioId, current.folioId);
  assert.equal(model().quickAction.kind, 'checkout');
  assert.equal(model().quickAction.stayId, stay.id);
  assert.deepEqual(model().previousAccounts, [old]);
  assert.equal(model({ ...room, status: 'cleaning' }).quickAction.kind, 'clean');
  assert.ok(model({ ...room, status: 'cleaning' }).quickAction.disabledReason);
  assert.equal(model({ ...room, status: 'maintenance' }).quickAction, undefined);
  assert.equal(model({ ...room, isActive: false }).quickAction, undefined);
  assert.equal(model(room, { ...summary, stays: [{ ...stay, checkOutDate: '2030-01-02' }] }).quickAction.kind, 'checkout');
  const planned = { ...stay, status: 'planned' };
  assert.equal(model(room, { ...summary, stays: [planned] }).quickAction, undefined);
  assert.equal(model(room, { ...summary, stays: [planned, { ...planned, id: 'conflicting' }] }).quickAction, undefined);
  assert.equal(model(room, { ...summary, stays: [] }).upcoming.id, reservation.id);
  assert.equal(model(room, { ...summary, stays: [], reservations: [reservation, { ...reservation, id: 'same-customer-conflict' }] }).quickAction, undefined);
  assert.equal(model(room, { ...summary, stays: [], reservations: [] }).previousAccounts[0].folioId, old.folioId);
  assert.equal(model(room, { ...summary, stays: [], reservations: [], accounts: [] }).quickAction, undefined);
  assert.equal(roomModel(room, undefined, caps, '2030-01-02').quickAction, undefined);
  assert.equal(model(room, summary, { staysEnabled: false, reservationsEnabled: false, folioEnabled: false }).quickAction, undefined);
  const table = { id: 'table', status: 'available', isActive: true };
  const tableSummary = { tableId: table.id, order: null, reservations: [] };
  const tm = (t = table, s = tableSummary, c = caps) => tableModel(t, s, c, '2030-01-02');
  assert.equal(tm().quickAction.kind, 'start');
  assert.equal(tableModel(table, undefined, caps, '2030-01-02').quickAction, undefined);
  for (const status of ['maintenance', 'out_of_service']) assert.equal(tm({ ...table, status }).quickAction, undefined);
  assert.equal(tm({ ...table, status: 'cleaning' }).quickAction.kind, 'clean');
  assert.equal(tm(table, tableSummary, { ...caps, ordersEnabled: false }).quickAction, undefined);
  for (const [status, kind] of [['preparing', 'served'], ['served', 'payment']]) assert.equal(tm(table, { ...tableSummary, order: { id: 'order', status } }).quickAction.kind, kind);
  const paymentModel = tm(table, { ...tableSummary, order: { id: 'order', status: 'payment' } });
  assert.equal(paymentModel.quickAction.kind, 'paid');
  assert.equal(paymentModel.order.id, 'order');
  const booking = { ...reservation, startDate: '2030-01-02', time: '19:00' };
  assert.equal(tm(table, { ...tableSummary, reservations: [booking, { ...booking, id: 'different-slot', time: '20:00' }] }).quickAction.kind, 'start');
  assert.equal(tm(table, { ...tableSummary, reservations: [booking, { ...booking, id: 'same-slot' }] }).quickAction, undefined);
  console.log('operations-card-models-ok: quick actions, account identity, conflicts, physical constraints, capabilities, unknown summary');
} finally { await server.close(); }
