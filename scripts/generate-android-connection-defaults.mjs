import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(repoRoot, "apps", "android-app");
const connectionConfigPath = join(appDir, "connection.local.json");
const outputPath = join(
  appDir,
  "build",
  "generated",
  "source",
  "connection",
  "com",
  "yardimciasistan",
  "android",
  "ConnectionDefaults.java"
);
const productionWebModuleUrl = "https://yardimciasistan.alwaysdata.net/yardimci-asistan";
const releaseBuild = truthy(process.env.YARDIMCI_ASISTAN_ANDROID_RELEASE_BUILD);
const allowEmbeddedSyncSecret = truthy(process.env.YARDIMCI_ASISTAN_ANDROID_ALLOW_EMBEDDED_SYNC_SECRET);

let localConfig = {};
if (existsSync(connectionConfigPath)) {
  try {
    localConfig = JSON.parse(readFileSync(connectionConfigPath, "utf8"));
  } catch (error) {
    throw new Error(
      `Android bağlantı dosyası okunamadı: ${error instanceof Error ? error.message : String(error)}`,
      { cause: error }
    );
  }
}

const webModuleUrl = normalizeWebModuleUrl(
  firstNonEmpty(
    process.env.YARDIMCI_ASISTAN_ANDROID_WEB_MODULE_URL,
    localConfig.web_module_url,
    productionWebModuleUrl
  )
);
const configuredSyncSecret = firstNonEmpty(
  process.env.YARDIMCI_ASISTAN_ANDROID_SYNC_SECRET,
  localConfig.sync_secret
);
const syncSecret = releaseBuild && !allowEmbeddedSyncSecret ? "" : configuredSyncSecret;
const generatedAt = new Date().toISOString();

if (!webModuleUrl) {
  throw new Error("Android bağlantısı için web_module_url gerekli.");
}
if (!/^https?:\/\//i.test(webModuleUrl)) {
  throw new Error(`Android web_module_url http/https olmalı: ${webModuleUrl}`);
}
if (releaseBuild && configuredSyncSecret && !allowEmbeddedSyncSecret) {
  console.warn("Android release build: sync_secret APK içine gömülmedi; cihaz eşleştirme akışı kullanılacak.");
}
if (releaseBuild && configuredSyncSecret && allowEmbeddedSyncSecret) {
  console.warn("UYARI: Android release build sync_secret içeriyor; bu yalnız kontrollü test dağıtımı için kullanılmalı.");
}

const javaSource = `// Generated by scripts/generate-android-connection-defaults.mjs at ${generatedAt}
package com.yardimciasistan.android;

final class ConnectionDefaults {
    static final String WEB_MODULE_URL = ${javaString(webModuleUrl)};
    static final String SYNC_SECRET = ${javaString(syncSecret)};

    private ConnectionDefaults() {}
}
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, javaSource, "utf8");
console.log(`Android connection defaults generated: ${outputPath}`);
console.log(`  web_module_url=${webModuleUrl}`);
console.log(`  sync_secret=${syncSecret ? `configured (${syncSecret.length} chars)` : "empty"}`);
console.log(`  release_build=${releaseBuild ? "yes" : "no"}`);

function firstNonEmpty(...values) {
  for (const value of values) {
    const normalized = String(value ?? "").trim();
    if (normalized) {
      return normalized;
    }
  }
  return "";
}

function normalizeWebModuleUrl(value) {
  return firstNonEmpty(value)
    .replace(/[\u0000-\u001F\u007F]/g, "")
    .replace(/\/+$/, "");
}

function truthy(value) {
  return ["1", "true", "yes", "on"].includes(String(value ?? "").trim().toLowerCase());
}

function javaString(value) {
  return JSON.stringify(String(value ?? ""));
}
