import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(
  repoRoot, "apps", "android-app", "build", "generated", "source",
  "connection", "com", "yardimciasistan", "android", "ConnectionDefaults.java"
);

// The APK is business-agnostic. No Web address or shared secret is compiled
// into either debug or release builds. User-directed pairing owns credentials.
const source = `// Generated by scripts/generate-android-connection-defaults.mjs
package com.yardimciasistan.android;

final class ConnectionDefaults {
    static final String WEB_MODULE_URL = "";
    static final String SYNC_SECRET = "";
    static final boolean LOCK_EMBEDDED_CONNECTION = false;

    private ConnectionDefaults() {}
}
`;
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, source, "utf8");
console.log("Android connection defaults generated without embedded business credentials.");
