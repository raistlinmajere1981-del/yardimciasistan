import assert from "node:assert/strict";
import { resolve } from "node:path";
import { chromium, expect } from "@playwright/test";
import { createServer } from "vite";
import { launchChromiumForSmoke } from "./test-helpers/playwright-browser.mjs";

const server = await createServer({ root: resolve("apps/desktop-app"), configFile: resolve("apps/desktop-app/vite.renderer.config.ts"), server: { port: 0, strictPort: false } });
await server.listen();
let browser;
try {
  browser = await launchChromiumForSmoke(chromium);
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, locale: "tr-TR" });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/ui-family-test", async route => route.fulfill({ contentType: "text/html", body: await server.transformIndexHtml("/ui-family-test", `<html><body><div id="root"></div><script type="module" src="/@fs/${resolve("scripts/fixtures/desktop-ui-family.tsx")}"></script></body></html>`) }));
  await page.goto(`${server.resolvedUrls.local[0]}ui-family-test`);
  const trigger = page.getByRole("button", { name: "Formu aç", exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "UI ailesi", exact: true });
  await expect(dialog.getByRole("heading", { name: "UI ailesi" })).toBeFocused();
  await dialog.getByRole("button", { name: "Tarih", exact: true }).click();
  const calendar = page.getByRole("dialog", { name: "Tarih seçici", exact: true });
  await expect(calendar.getByText("Ekim 2026", { exact: true })).toBeVisible();
  await expect(calendar.getByRole("button", { name: "Sınır dışında", exact: true })).toBeDisabled();
  await calendar.getByRole("button", { name: "Yarın", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Tarih", exact: true })).toBeFocused();
  await expect(dialog.getByLabel("Seçilen zaman")).toHaveText("2026-10-19 09:15");
  await dialog.getByRole("button", { name: "Tarih", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(calendar).toHaveCount(0);
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Saat", exact: true }).click();
  const clock = page.getByRole("dialog", { name: "Saat seçici", exact: true });
  await clock.getByRole("listbox", { name: "Saat", exact: true }).getByRole("option", { name: "10", exact: true }).click();
  await clock.getByRole("listbox", { name: "Dakika", exact: true }).getByRole("option", { name: "45", exact: true }).click();
  await expect(dialog.getByLabel("Seçilen zaman")).toHaveText("2026-10-19 10:45");
  await expect(dialog.getByRole("button", { name: "Saat", exact: true })).toBeFocused();
  const remove = dialog.getByRole("button", { name: "Örneği kaldır", exact: true });
  await dialog.getByRole("button", { name: "Meşgul durumunu değiştir", exact: true }).click();
  await expect(remove).toBeDisabled();
  await expect(remove).toHaveAttribute("aria-busy", "true");
  await expect(dialog.getByLabel("Kaldırma sayısı")).toHaveText("0");
  await dialog.getByRole("button", { name: "Meşgul durumunu değiştir", exact: true }).click();
  await remove.click();
  await expect(dialog.getByLabel("Kaldırma sayısı")).toHaveText("1");
  await expect(dialog.getByRole("button", { name: "Görsel 1 yukarı", exact: true })).toBeDisabled();
  await expect(dialog.getByRole("button", { name: "Görsel 2 aşağı", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Görsel 2 yukarı", exact: true }).click();
  await expect(dialog.getByLabel("Görsel sırası")).toHaveText("b,a");
  const colors = [];
  for (const scheme of ["light", "dark"]) for (const density of ["compact", "comfortable"]) {
    await page.evaluate(({scheme,density}) => window.appearance(scheme,density,1.1), {scheme,density});
    await page.keyboard.press("Tab");
    await remove.focus();
    await expect(remove).toBeFocused();
    const style = await remove.evaluate(el => { const s=getComputedStyle(el); return {outline:s.outlineStyle,background:s.backgroundColor}; });
    assert.equal(style.outline, "solid");
    colors.push(style.background);
    const targets = await dialog.locator(".action-button, .icon-button").evaluateAll(elements => elements.map(el => ({label:el.getAttribute("aria-label")||el.textContent,rect:el.getBoundingClientRect()})).filter(({rect}) => rect.width < 44 || rect.height < 44).map(({label}) => label));
    assert.deepEqual(targets, [], `${scheme}/${density}: full action targets`);
    const preview = dialog.getByAltText("Oran örneği");
    await expect(preview).toBeVisible();
    const media = await preview.evaluate(img => ({fit:getComputedStyle(img).objectFit,width:img.getBoundingClientRect().width,height:img.getBoundingClientRect().height}));
    assert.equal(media.fit,"contain");
    assert.ok(Math.abs(media.width/media.height-2)<0.01,"preview keeps the source aspect ratio");
  }
  assert.notEqual(colors[0],colors[2],"light/dark use different semantic surfaces");
  await dialog.getByRole("button", { name: "Tamam", exact: true }).click();
  await expect(trigger).toBeFocused();
  assert.deepEqual(errors,[]);
  console.log("desktop-ui-family-smoke-ok: Turkish date/time, focus, busy actions, ordering, media ratio and four appearance combinations");
} finally { await browser?.close(); await server.close(); }
